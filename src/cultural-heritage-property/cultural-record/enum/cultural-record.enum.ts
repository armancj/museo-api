/**
 * Enumeration for value grade levels.
 *
 * Represents different grading levels for cultural objects, typically used to
 * classify or evaluate the significance or value of an item.
 */
export enum ValueGrade {
  /** Highest grade or level of value */
  I = 'I',

  /** Intermediate grade or level of value */
  II = 'II',

  /** Lower grade or level of value */
  III = 'III',
}

/**
 * Enumeration for description levels.
 *
 * Specifies different levels of description detail for cultural objects, indicating the depth or extent of information provided.
 */
export enum DescriptionLevel {
  /** Level 1: Broadest or most general description level */
  Level1 = 1,

  /** Level 2: Intermediate description level */
  Level2 = 2,

  /** Level 3: Most detailed description level */
  Level3 = 3,
}
